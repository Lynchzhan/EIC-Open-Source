def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()


def public_template(item):
    return {k: v for k, v in item.items() if k != "legacy"}


def content_digest(name, prompt, description):
    return digest({"name": name, "prompt": prompt, "description": description})


